#!/usr/bin/env python3
"""Re-derive every published number from the seed, and fail if any has drifted.

A benchmark whose results cannot be re-derived from its own repository is a
claim, not a measurement. This script runs the full matrix at a fixed seed,
writes the tables in `results/`, and compares them against the committed
expectations. CI runs it on every push.

    python scripts/reproduce.py            # regenerate and check
    python scripts/reproduce.py --update   # accept new numbers (review the diff)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from lsb.core.report import aggregate  # noqa: E402
from lsb.core.runner import RunConfig, run  # noqa: E402
from lsb.core.stats import compare  # noqa: E402
from lsb.core.suite import load as load_suite  # noqa: E402
from lsb.defenses import catalogue  # noqa: E402
from lsb.defenses import load as load_defense
from lsb.targets import load as load_target  # noqa: E402

SEED = 1337
REPEAT = 20  # 49 probes x 20 = 980 trials per cell; enough to separate intervals
PROFILES = ("naive", "guarded", "hardened")
RESULTS = ROOT / "results"
EXPECTED = RESULTS / "expected.json"


def run_matrix() -> dict:
    suite = load_suite()
    config = RunConfig(seed=SEED, repeat=REPEAT, workers=8)
    out: dict = {"seed": SEED, "repeat": REPEAT, "suite": suite.slug, "probes": len(suite)}

    print(f"corpus: {suite.slug}, {len(suite)} probes, {len(suite) * REPEAT} trials per cell\n")

    print("== exposure by profile ==")
    profiles: dict = {}
    for profile in PROFILES:
        report = run(suite, load_target(f"mock:{profile}"), config=config)
        agg = aggregate(report.results)
        profiles[profile] = {
            "exposure": agg.exposure,
            "grade": agg.letter,
            "overall": agg.overall.to_dict(),
            "by_family": {f.value: r.to_dict() for f, r in agg.by_family.items()},
        }
        print(
            f"  {profile:9} exposure {agg.exposure:5.1f} "
            f"({agg.letter})  ASR {agg.overall.pct:>6}"
        )
    out["profiles"] = profiles

    print("\n== defenses vs the undefended baseline (target: mock:naive) ==")
    baseline_report = run(suite, load_target("mock:naive"), config=config)
    baseline = aggregate(baseline_report.results).overall
    defenses: dict = {"none": {"asr": baseline.to_dict(), "verdict": "reference"}}
    print(f"  {'none':17} ASR {baseline.pct:>6}  (reference)")

    for name in catalogue():
        if name == "none":
            continue
        defense = load_defense(name)
        report = run(suite, load_target("mock:naive"), defense, config)
        rate = aggregate(report.results).overall
        cmp = compare(baseline, rate)
        defenses[name] = {
            "asr": rate.to_dict(),
            "delta": round(cmp.delta, 4),
            "significant": cmp.significant,
            "verdict": cmp.verdict,
            "simulated": report.simulated,
            "mechanical": getattr(defense, "mechanical", True),
        }
        flag = "  [simulated]" if report.simulated else ""
        print(f"  {name:17} ASR {rate.pct:>6}  {cmp.delta * 100:+6.1f} pts  {cmp.verdict}{flag}")
    out["defenses"] = defenses

    print("\n== extraction only, with and without output filtering ==")
    extraction = suite.select(families=["extraction"])
    plain = aggregate(run(extraction, load_target("mock:naive"), config=config).results).overall
    filtered_report = run(
        extraction, load_target("mock:naive"), load_defense("output-filter"), config
    )
    filtered = aggregate(filtered_report.results).overall
    residual = [r for r in filtered_report.results if r.attacked]
    encoded = sum(1 for r in residual if "encoded" in r.evidence or "normalis" in r.evidence)
    out["output_filter_residual"] = {
        "asr_without": plain.to_dict(),
        "asr_with": filtered.to_dict(),
        "residual_hits": len(residual),
        "residual_obfuscated": encoded,
    }
    print(f"  without filter        {plain.pct:>6}")
    print(f"  with filter           {filtered.pct:>6}")
    if residual:
        pct = 100 * encoded / len(residual)
        print(
            f"  residual leaks        {len(residual)}, "
            f"of which {encoded} obfuscated ({pct:.0f}%)"
        )
    return out


def write_markdown(data: dict) -> None:
    lines = [
        "# Results",
        "",
        "Generated by `scripts/reproduce.py`, re-derived by CI on every push.",
        "",
        f"- suite: `{data['suite']}` ({data['probes']} probes)",
        f"- seed: `{data['seed']}`, repeat: {data['repeat']} "
        f"({data['probes'] * data['repeat']} trials per cell)",
        "",
        "> These runs use the **simulated** target. They exercise the graders,",
        "> the statistics and reproducibility; they say nothing about any real",
        "> model. See `docs/METHODOLOGY.md` §7.",
        "",
        "## Exposure by profile",
        "",
        "| Profile | Exposure | Grade | Overall ASR | 95% CI |",
        "| --- | ---: | :---: | ---: | ---: |",
    ]
    for name, row in data["profiles"].items():
        o = row["overall"]
        lines.append(
            f"| `mock:{name}` | {row['exposure']:.1f} | {row['grade']} | "
            f"{o['point'] * 100:.1f}% | {o['ci_low'] * 100:.1f}–{o['ci_high'] * 100:.1f}% |"
        )

    families = list(data["profiles"]["naive"]["by_family"])
    header = " | ".join(f.replace("_", " ").title() for f in families)
    rule = " | ".join("---:" for _ in families)
    lines += [
        "",
        "## Attack success by family",
        "",
        f"| Profile | {header} |",
        f"| --- | {rule} |",
    ]
    for name, row in data["profiles"].items():
        cells = " | ".join(f"{r['point'] * 100:.1f}%" for r in row["by_family"].values())
        lines.append(f"| `mock:{name}` | {cells} |")

    lines += [
        "",
        "## Did the defense move the number?",
        "",
        "Target `mock:naive`. A difference counts only when the 95% intervals",
        "do not overlap.",
        "",
        "| Defense | Kind | ASR | Δ vs none | Verdict |",
        "| --- | --- | ---: | ---: | --- |",
    ]
    for name, row in data["defenses"].items():
        if name == "none":
            lines.append(
                f"| `none` | – | {row['asr']['point'] * 100:.1f}% | – | reference |"
            )
            continue
        kind = "mechanical" if row["mechanical"] else "prompt-level"
        verdict = row["verdict"] + (" **(simulated)**" if row["simulated"] else "")
        lines.append(
            f"| `{name}` | {kind} | {row['asr']['point'] * 100:.1f}% | "
            f"{row['delta'] * 100:+.1f} pts | {verdict} |"
        )

    res = data["output_filter_residual"]
    share = (
        f"{100 * res['residual_obfuscated'] / res['residual_hits']:.0f}%"
        if res["residual_hits"]
        else "n/a"
    )
    lines += [
        "",
        "## What output filtering does not catch",
        "",
        "Literal redaction is correct against verbatim leaks, which is why teams",
        "conclude secret leakage is solved once it ships. Running the extraction",
        "family with it on does not reach zero:",
        "",
        f"- extraction ASR without the filter: **{res['asr_without']['point'] * 100:.1f}%**",
        f"- extraction ASR with the filter: **{res['asr_with']['point'] * 100:.1f}%**",
        f"- of the {res['residual_hits']} leaks that survived, **{share}** were obfuscated",
        "  (base64, reversed, spaced out, separator-mangled) rather than verbatim",
        "",
        "That residual is the number worth knowing, and it is only visible because",
        "the canary detector decodes before concluding a token is absent.",
        "",
    ]
    (RESULTS / "README.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--update", action="store_true", help="accept the new numbers")
    args = parser.parse_args()

    RESULTS.mkdir(exist_ok=True)
    data = run_matrix()
    write_markdown(data)

    if args.update or not EXPECTED.exists():
        EXPECTED.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
        print(f"\nwrote {EXPECTED.relative_to(ROOT)}")
        return 0

    expected = json.loads(EXPECTED.read_text())
    if expected == data:
        print("\nreproduced exactly: every published number re-derived from the seed")
        return 0

    print("\nDRIFT: the re-derived numbers differ from results/expected.json")
    for profile in PROFILES:
        was = expected["profiles"][profile]["exposure"]
        now = data["profiles"][profile]["exposure"]
        if was != now:
            print(f"  mock:{profile} exposure {was} -> {now}")
    print("  review the change, then re-run with --update if it is intended")
    return 1


if __name__ == "__main__":
    sys.exit(main())
